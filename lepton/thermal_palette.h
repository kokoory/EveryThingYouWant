/**
 * @brief Apply color palette to grayscale thermal image, output as RGB BMP pixel data.
 *
 * @param gray_in    Input grayscale buffer (width*height bytes)
 * @param rgb_out    Output RGB buffer (width*height*3 bytes, BGR order for BMP)
 * @param num_pixels Total number of pixels
 * @param palette    Color palette to use (e.g., palette_ironbow)
 */
static inline void thermal_apply_palette(const uint8_t *gray_in, uint8_t *rgb_out,
                                         int num_pixels, const uint8_t palette[][3])
{
    for (int i = 0; i < num_pixels; i++)
    {
        uint8_t val = gray_in[i];
        /* BMP uses BGR order */
        rgb_out[i * 3 + 0] = palette[val][2]; /* B */
        rgb_out[i * 3 + 1] = palette[val][1]; /* G */
        rgb_out[i * 3 + 2] = palette[val][0]; /* R */
    }
}

